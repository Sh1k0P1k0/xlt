#!/usr/bin/env python3
"""Shift-JIS tables for src/fsname.c: bake_sjis.py OUT.h

The PSP's FAT driver gives and takes file names in Shift-JIS (Microsoft's
cp932). Three tables:
  sjis_fwd[60][189]  two-byte Shift-JIS -> Unicode (lead 81-9F, E0-FC; trail 40-FC), 0 = none
  sjis_rev[]         Unicode -> Shift-JIS, sorted by code point (a byte < 0x100: one byte)
  sjis_sub[]         what to write for a character Shift-JIS lacks: XLT Tool's choice
                     (tools/xltlink.py psp_name: the letter without its accent, - for
                     dashes, ' for quotes, ...), so XLT and XLT Tool name files alike
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xltlink  # noqa: E402  (its naming only: no USB needed)

out = sys.argv[1]
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = list(range(0x40, 0xFD))  # 189 (0x7F included, never a valid trail: stays 0)

fwd = []
for lead in LEADS:
    row = []
    for trail in TRAILS:
        try:
            ch = bytes([lead, trail]).decode("cp932")
            row.append(ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0)
        except UnicodeDecodeError:
            row.append(0)
    fwd.append(row)

rev = {}
for cp in range(0x80, 0x10000):
    if 0xD800 <= cp < 0xE000:
        continue
    try:
        b = chr(cp).encode("cp932")
    except UnicodeEncodeError:
        continue
    rev[cp] = b[0] if len(b) == 1 else b[0] << 8 | b[1]

sub = []
for cp in range(0x80, 0x3000):  # Latin, Greek, Cyrillic, punctuation, symbols
    if cp in rev or 0xD800 <= cp < 0xE000:
        continue
    ch = chr(cp)
    if not ch.isprintable():
        continue
    s = xltlink.psp_name("x" + ch + "x")[1:-1]  # inside a name: no trimming of the ends
    if not s or s == "_":
        continue
    b = s.encode("cp932")
    if len(b) <= 5:
        sub.append((cp, b))

with open(out, "w") as f:
    f.write("/* Generated by tools/bake_sjis.py - do not edit. */\n")
    f.write("static const unsigned short sjis_fwd[60][189] = {\n")
    for row in fwd:
        f.write("{" + ",".join(str(v) for v in row) + "},\n")
    f.write("};\n")
    f.write(f"#define SJIS_REV_N {len(rev)}\n")
    f.write("static const unsigned short sjis_rev[SJIS_REV_N][2] = {\n")
    items = sorted(rev.items())
    for i in range(0, len(items), 8):
        f.write(",".join(f"{{{c},{s}}}" for c, s in items[i:i + 8]) + ",\n")
    f.write("};\n")
    f.write(f"#define SJIS_SUB_N {len(sub)}\n")
    f.write("static const struct { unsigned short cp; unsigned char len, b[5]; } sjis_sub[SJIS_SUB_N] = {\n")
    for cp, b in sub:
        f.write(f"{{{cp},{len(b)},{{{','.join(str(x) for x in b)}}}}},\n")
    f.write("};\n")
print(f"{out}: {len(rev)} characters, {len(sub)} substitutes", file=sys.stderr)
